#!/usr/bin/env bash
# content-web dev stack for Keycast, without Docker: native Postgres and Valkey
# (or Redis) on loopback ports 4300-4302. DEVELOPMENT ONLY: it uses the local
# file master key, which must never be used in production.
#
#   scripts/content-web-dev.sh init     # once: database, master key, secrets file
#   scripts/content-web-dev.sh build    # debug build of the keycast binary
#   scripts/content-web-dev.sh start    # Postgres, Valkey, migrations, Keycast
#   scripts/content-web-dev.sh stop     # stops all three, by PID
#   scripts/content-web-dev.sh status
#   scripts/content-web-dev.sh test [cargo test args...]   # Postgres + Valkey must be running
#
# Secrets live in .dev/dev.env (mode 600, gitignored) and are never printed.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEV="${KEYCAST_DEV_DIR:-$ROOT/.dev}"
PG_BIN="${PG_BIN:-$(ls -d /usr/lib/postgresql/*/bin 2>/dev/null | sort -V | tail -1)}"
VALKEY="$(command -v valkey-server || command -v redis-server || true)"
PG_PORT=4301
VALKEY_PORT=4302
KEYCAST_PORT=4300

# Keycast's 1-second bcrypt admission waits assume an optimised bcrypt. In an
# unoptimised debug build on a Raspberry Pi a cost-10 hash takes longer, so
# tests and logins time out with 503s. Optimise just those two crates.
CARGO_PI_FLAGS=(--config 'profile.dev.package.blowfish.opt-level=3' --config 'profile.dev.package.bcrypt.opt-level=3')

die() { echo "content-web-dev: $*" >&2; exit 1; }
rand_hex() { od -An -N"$1" -tx1 /dev/urandom | tr -d ' \n'; }
pid_alive() { [ -f "$1" ] && kill -0 "$(head -1 "$1")" 2>/dev/null; }

load_env() {
  [ -f "$DEV/dev.env" ] || die "run '$0 init' first"
  set -a; . "$DEV/dev.env"; set +a
}

init() {
  [ -x "$PG_BIN/initdb" ] || die "Postgres binaries not found (apt install postgresql)"
  [ -n "$VALKEY" ] || die "valkey-server or redis-server not found (apt install valkey-server)"
  umask 077
  mkdir -p "$DEV/run" "$DEV/logs"
  chmod 700 "$DEV"
  if [ ! -f "$ROOT/master.key" ]; then
    (cd "$ROOT" && ./scripts/generate_key.sh >/dev/null)
  fi
  if [ ! -f "$DEV/dev.env" ]; then
    local pg_password; pg_password="$(rand_hex 24)"
    cat > "$DEV/dev.env" <<EOF
# Generated by scripts/content-web-dev.sh. Dev-only throwaway values. Never commit.
DATABASE_URL=postgres://postgres:${pg_password}@127.0.0.1:${PG_PORT}/keycast
TEST_DATABASE_URL=postgres://postgres:${pg_password}@127.0.0.1:${PG_PORT}/keycast_test
REDIS_URL=redis://127.0.0.1:${VALKEY_PORT}
TEST_REDIS_URL=redis://127.0.0.1:${VALKEY_PORT}/1
SERVER_NSEC=$(rand_hex 32)
KEYCAST_HELD_KEY_SERVICE_TOKEN=$(rand_hex 32)
KMS_PROVIDER=file
MASTER_KEY_PATH=${ROOT}/master.key
PORT=${KEYCAST_PORT}
BIND_ADDRESS=127.0.0.1
APP_URL=http://127.0.0.1:${KEYCAST_PORT}
ALLOWED_ORIGINS=http://127.0.0.1:${KEYCAST_PORT}
BUNKER_RELAYS=ws://127.0.0.1:7777
HELD_KEY_PROFILE_RELAYS=ws://127.0.0.1:7777
ENABLE_DEV_EMAIL_INBOX=true
ALLOWED_TENANT_DOMAINS=localhost
ENABLE_TENANT_AUTO_PROVISIONING=true
RUST_LOG=info,sqlx=warn
EOF
    printf '%s' "$pg_password" > "$DEV/pg.pass"
  fi
  if [ ! -d "$DEV/pg" ]; then
    "$PG_BIN/initdb" -D "$DEV/pg" -U postgres --pwfile="$DEV/pg.pass" --auth=scram-sha-256 >"$DEV/logs/initdb.log"
  fi
  start_deps
  load_env
  for db in keycast keycast_test; do
    if ! PGPASSWORD="$(cat "$DEV/pg.pass")" "$PG_BIN/psql" -h 127.0.0.1 -p $PG_PORT -U postgres -tAc \
        "SELECT 1 FROM pg_database WHERE datname = '$db'" | grep -q 1; then
      PGPASSWORD="$(cat "$DEV/pg.pass")" "$PG_BIN/createdb" -h 127.0.0.1 -p $PG_PORT -U postgres "$db"
    fi
  done
  echo "init done: $DEV (secrets in dev.env, mode 600)"
}

start_deps() {
  if ! "$PG_BIN/pg_ctl" -D "$DEV/pg" status >/dev/null 2>&1; then
    "$PG_BIN/pg_ctl" -D "$DEV/pg" -l "$DEV/logs/postgres.log" -w \
      -o "-p $PG_PORT -c listen_addresses=127.0.0.1 -k $DEV/run" start >/dev/null
  fi
  if ! pid_alive "$DEV/run/valkey.pid"; then
    "$VALKEY" --port $VALKEY_PORT --bind 127.0.0.1 --protected-mode yes --save '' --appendonly no \
      --daemonize yes --pidfile "$DEV/run/valkey.pid" --logfile "$DEV/logs/valkey.log" --dir "$DEV/run"
    for _ in $(seq 1 50); do pid_alive "$DEV/run/valkey.pid" && break; sleep 0.1; done
  fi
}

start() {
  start_deps
  load_env
  local bin="$ROOT/target/debug/keycast"
  [ -x "$bin" ] || die "build first: $0 build"
  (cd "$ROOT" && "$bin" --migrate >>"$DEV/logs/keycast.log" 2>&1)
  if pid_alive "$DEV/run/keycast.pid"; then
    echo "keycast already running (pid $(cat "$DEV/run/keycast.pid"))"
  else
    # Record the binary's own PID (nohup execs it), so stop can kill it by PID.
    cd "$ROOT"
    nohup "$bin" >>"$DEV/logs/keycast.log" 2>&1 </dev/null &
    echo $! > "$DEV/run/keycast.pid"
    local healthy=no
    for _ in $(seq 1 200); do
      pid_alive "$DEV/run/keycast.pid" || break
      if curl -fsS "http://127.0.0.1:$KEYCAST_PORT/health" >/dev/null 2>&1; then healthy=yes; break; fi
      sleep 0.3
    done
    if [ "$healthy" != yes ]; then
      status
      die "keycast did not become healthy; see $DEV/logs/keycast.log"
    fi
  fi
  status
}

stop() {
  if pid_alive "$DEV/run/keycast.pid"; then
    kill "$(cat "$DEV/run/keycast.pid")"
    for _ in $(seq 1 100); do pid_alive "$DEV/run/keycast.pid" || break; sleep 0.2; done
  fi
  rm -f "$DEV/run/keycast.pid"
  if pid_alive "$DEV/run/valkey.pid"; then kill "$(cat "$DEV/run/valkey.pid")"; fi
  if [ -d "$DEV/pg" ] && "$PG_BIN/pg_ctl" -D "$DEV/pg" status >/dev/null 2>&1; then
    "$PG_BIN/pg_ctl" -D "$DEV/pg" -m fast -w stop >/dev/null
  fi
  status
}

status() {
  local pg="stopped" vk="stopped" kc="stopped"
  [ -d "$DEV/pg" ] && "$PG_BIN/pg_ctl" -D "$DEV/pg" status >/dev/null 2>&1 && pg="running on 127.0.0.1:$PG_PORT"
  pid_alive "$DEV/run/valkey.pid" && vk="running on 127.0.0.1:$VALKEY_PORT (pid $(cat "$DEV/run/valkey.pid"))"
  pid_alive "$DEV/run/keycast.pid" && kc="running on http://127.0.0.1:$KEYCAST_PORT (pid $(cat "$DEV/run/keycast.pid"))"
  echo "postgres: $pg"
  echo "valkey:   $vk"
  echo "keycast:  $kc"
}

build() {
  cd "$ROOT"
  cargo build "${CARGO_PI_FLAGS[@]}" --bin keycast
}

run_tests() {
  load_env
  export DATABASE_URL="$TEST_DATABASE_URL"
  cd "$ROOT"
  cargo test "${CARGO_PI_FLAGS[@]}" --workspace \
    --features keycast_core/integration-tests,keycast_api/integration-tests,keycast_signer/integration-tests \
    "$@"
}

case "${1:-}" in
  init) init ;;
  start) start ;;
  stop) stop ;;
  status) status ;;
  build) build ;;
  test) shift; run_tests "$@" ;;
  *) sed -n '2,13p' "$0"; exit 1 ;;
esac
